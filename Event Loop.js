// Демонстрация работы Event Loop

console.log('Начало скрипта'); // 1. Синхронный код выполняется первым

setTimeout(() => {
  console.log('setTimeout с задержкой 0'); // 5. Макрозадача выполняется после микрозадач
}, 0);

Promise.resolve()
  .then(() => {
    console.log('Promise 1'); // 3. Микрозадача выполняется после синхронного кода
  })
  .then(() => {
    console.log('Promise 2'); // 4. Следующая микрозадача в цепочке
  });

console.log('Конец скрипта'); // 2. Синхронный код продолжает выполняться

/*
Порядок выполнения:
1. Все синхронные console.log
2. Затем микрозадачи из Promise (then)
3. И только потом макрозадачи из setTimeout
*/
